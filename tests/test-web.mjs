import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const sandbox = {};
vm.runInNewContext(fs.readFileSync(new URL("../web/inventory.js", import.meta.url), "utf8"), sandbox);
const kit = sandbox.WadayaInventory;
const item = { item_id: "B001", room: "Kitchen", description: 'Cups, "plates"\nand bowls', length_cm: 60, width_cm: 40, height_cm: 40, quantity: 1 };
assert.equal(kit.packedVolume(kit.normalizeItem(item)), 0.096);
assert.ok(Math.abs(kit.packedVolume(kit.normalizeItem({ ...item, length_cm: 60.5, quantity: 3 })) - 0.2904) < 1e-12);
for (const value of [0, -1, "NaN", "Infinity", "large", ""]) assert.throws(() => kit.normalizeItem({ ...item, length_cm: value }), /dimensions/);
for (const quantity of [0, -1, 1.5]) assert.throws(() => kit.normalizeItem({ ...item, quantity }), /whole number/);
assert.throws(() => kit.validateInventory([item, item]), /unique/);
const exported = kit.toCsv([item]);
const restored = kit.fromCsv(exported)[0];
assert.equal(restored.description, item.description);
assert.equal(restored.length_cm, 60);
assert.equal(kit.fromCsv("\ufeff" + exported)[0].item_id, "B001");
assert.equal(kit.packedVolume(kit.fromCsv(exported.replace(",0.096", ",999"))[0]), 0.096);
assert.throws(() => kit.fromCsv(exported + '"unterminated'), /never closes/);
assert.throws(() => kit.fromCsv("item_id,room\nB001,Kitchen"), /columns/);
for (const description of ["=1+2", "+SUM(1,2)", "-1+2", "@SUM(1,2)", "\t=1+2"]) assert.ok(kit.fromCsv(kit.toCsv([{ ...item, description }]))[0].description.startsWith("'"));
const example = kit.fromCsv(fs.readFileSync(new URL("../examples/example-inventory.csv", import.meta.url), "utf8"));
const summary = kit.summarize(example);
assert.equal(summary.count, 8);
assert.ok(Math.abs(summary.volume - 0.528) < 1e-12);
assert.ok(Math.abs(summary.rooms.get("Bedroom") - 0.288) < 1e-12);
const plannerHeader = "Box ID,Room,Decision,Contents,Open first,Length (cm),Width (cm),Height (cm),Volume (m3),Packed,Location,Notes\n";
const plannerRow = "B001,Kitchen,Store,Cups,No,60,40,40,999,Yes,Shelf 1,Handle carefully\n";
assert.equal(kit.fromCsv(plannerHeader + plannerRow)[0].quantity, 1);
assert.equal(kit.packedVolume(kit.fromCsv(plannerHeader + plannerRow)[0]), 0.096);
assert.throws(() => kit.fromCsv(plannerHeader + plannerRow.replace(",60,40,40,", ",,40,40,")), /fill in length, width and height for B001/);
process.stdout.write("Web arithmetic, input, CSV and spreadsheet-safety checks passed.\n");
